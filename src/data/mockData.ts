// Helper to compute all mesh connection links matching the exact Fan/Star pattern:
// 1. Within each zone, all 5 nodes connect to their local zone hub point (fanning out).
// 2. Each zone hub connects onward to the side-positioned Central Gateway.
export function getMeshConnections(nodes: SensorNode[], zones: MiningZone[], gateway: CentralGateway) {
  const connections: Array<{
    fromId: string;
    toId: string;
    fromCoords: [number, number];
    toCoords: [number, number];
    distanceM: number;
    type: 'NODE_TO_ZONE_HUB' | 'ZONE_HUB_TO_GATEWAY';
    label: string;
    zoneId: string;
  }> = [];

  // 1. Each node connects to its local Zone Hub (Fan / Star pattern)
  zones.forEach((zone) => {
    const zoneNodes = nodes.filter((n) => n.zoneId === zone.id);
    zoneNodes.forEach((node) => {
      const dist = haversineDistanceMeters(node.lat, node.lng, zone.hubCoords[0], zone.hubCoords[1]);
      connections.push({
        fromId: node.id,
        toId: `HUB-${zone.id}`,
        fromCoords: [node.lat, node.lng],
        toCoords: zone.hubCoords,
        distanceM: dist,
        type: 'NODE_TO_ZONE_HUB',
        label: `${dist} m`,
        zoneId: zone.id,
      });
    });

    // 2. Zone Hub connects onward to the Central Gateway (on the side)
    const hubToGwDist = haversineDistanceMeters(zone.hubCoords[0], zone.hubCoords[1], gateway.lat, gateway.lng);
    connections.push({
      fromId: `HUB-${zone.id}`,
      toId: gateway.id,
      fromCoords: zone.hubCoords,
      toCoords: [gateway.lat, gateway.lng],
      distanceM: hubToGwDist,
      type: 'ZONE_HUB_TO_GATEWAY',
      label: `${hubToGwDist} m`,
      zoneId: zone.id,
    });
  });

  return connections;
}
