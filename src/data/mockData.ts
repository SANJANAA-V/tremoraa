// Past 12 months helper
const MONTHS = ['Oct', 'Nov', 'Dec', 'Jan', 'Feb', 'Mar', 'Apr', 'May', 'Jun', 'Jul', 'Aug', 'Sep'];

function generateHistoricalReadings(baseElev: number, totalSubMm: number, currentRate: number) {
  return MONTHS.map((m, idx) => {
    const fraction = (idx + 1) / 12;
    const subMm = parseFloat((totalSubMm * Math.pow(fraction, 1.25)).toFixed(1));
    const elev = parseFloat((baseElev - subMm / 1000).toFixed(3));
    const rate = parseFloat((currentRate * (0.82 + 0.32 * fraction)).toFixed(1));
    return {
      month: `${m} 2025/26`,
      elevationM: elev,
      subsidenceMm: subMm,
      rateMmYr: rate,
    };
  });
}

